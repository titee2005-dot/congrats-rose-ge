-- ==========================================
-- SQL สำหรับตั้งค่าตารางคำอวยพร + ตั้งค่าเว็บออนไลน์ Rose BNK48 19th Birthday บน Supabase
-- (ทำให้การ์ดคำอวยพร จำนวนกระต่าย และวิดีโอช่อง Rose Birthday Party ซิงก์กันทุกคนแบบ Real-time)
-- ==========================================

-- 1. ตารางการ์ดคำอวยพร (rose_wishes)
create table if not exists public.rose_wishes (
  id bigint generated by default as identity primary key,
  bg text not null default 'pressed-rose',
  name text not null,
  message text not null,
  img text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'hidden')),
  created_at timestamptz not null default now()
);

alter table public.rose_wishes enable row level security;

create policy "Allow public select rose_wishes"
  on public.rose_wishes for select
  using (true);

create policy "Allow public insert rose_wishes"
  on public.rose_wishes for insert
  with check (true);

create policy "Allow public update rose_wishes"
  on public.rose_wishes for update
  using (true);

create policy "Allow public delete rose_wishes"
  on public.rose_wishes for delete
  using (true);

-- 2. ตารางตั้งค่าเว็บสำหรับหน้า /admin (จำนวนกระต่าย & วิดีโอ Rose Birthday Party)
create table if not exists public.rose_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.rose_settings enable row level security;

create policy "Allow public select rose_settings"
  on public.rose_settings for select
  using (true);

create policy "Allow public insert rose_settings"
  on public.rose_settings for insert
  with check (true);

create policy "Allow public update rose_settings"
  on public.rose_settings for update
  using (true);

insert into public.rose_settings (key, value)
values (
  'site_config',
  '{"bunny_mode":"auto","bunny_manual_count":3,"party_video_url":""}'::jsonb
)
on conflict (key) do nothing;

-- 3. เปิด Realtime ให้ทั้งสองตาราง
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'rose_wishes'
  ) then
    alter publication supabase_realtime add table public.rose_wishes;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'rose_settings'
  ) then
    alter publication supabase_realtime add table public.rose_settings;
  end if;
end $$;

-- 4. Storage Bucket สำหรับอัปโหลดวิดีโอช่อง Rose Birthday Party จากหน้า /admin
insert into storage.buckets (id, name, public, file_size_limit)
values ('rose-party-media', 'rose-party-media', true, 52428800)
on conflict (id) do nothing;

create policy "Allow public read rose_party_media"
  on storage.objects for select
  using (bucket_id = 'rose-party-media');

create policy "Allow public upload rose_party_media"
  on storage.objects for insert
  with check (bucket_id = 'rose-party-media');

create policy "Allow public update rose_party_media"
  on storage.objects for update
  using (bucket_id = 'rose-party-media');
