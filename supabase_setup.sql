-- 1. ตารางการ์ดแสดงความยินดี (rose_ge_wishes)
create table if not exists public.rose_ge_wishes (
  id bigint generated by default as identity primary key,
  bg text not null default 'royal-rose',
  stamp text not null default 'crown-gold',
  name text not null,
  message text not null,
  img text,
  likes integer not null default 0,
  is_featured boolean not null default false,
  status text not null default 'pending' check (status in ('pending', 'approved', 'hidden')),
  created_at timestamptz not null default now()
);

create index if not exists idx_rose_ge_wishes_status_created_at
  on public.rose_ge_wishes (status, created_at desc);

alter table public.rose_ge_wishes enable row level security;

create policy "Allow public select rose_ge_wishes"
  on public.rose_ge_wishes for select
  to anon, authenticated
  using (true);

create policy "Allow public insert rose_ge_wishes"
  on public.rose_ge_wishes for insert
  to anon, authenticated
  with check (true);

create policy "Allow public update rose_ge_wishes"
  on public.rose_ge_wishes for update
  to anon, authenticated
  using (true)
  with check (true);

create policy "Allow public delete rose_ge_wishes"
  on public.rose_ge_wishes for delete
  to anon, authenticated
  using (true);

