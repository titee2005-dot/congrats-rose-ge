-- 3. เปิด Realtime ให้ทั้งสองตาราง
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'rose_ge_wishes'
  ) then
    alter publication supabase_realtime add table public.rose_ge_wishes;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'rose_ge_settings'
  ) then
    alter publication supabase_realtime add table public.rose_ge_settings;
  end if;
end $$;

-- 4. Storage Bucket สำหรับอัปโหลดมีเดียเว็บแสดงความยินดี (rose-ge-media)
insert into storage.buckets (id, name, public, file_size_limit)
values ('rose-ge-media', 'rose-ge-media', true, 52428800)
on conflict (id) do nothing;

create policy "Allow public read rose_ge_media"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'rose-ge-media');

create policy "Allow public upload rose_ge_media"
  on storage.objects for insert
  to anon, authenticated
  with check (bucket_id = 'rose-ge-media');

create policy "Allow public update rose_ge_media"
  on storage.objects for update
  to anon, authenticated
  using (bucket_id = 'rose-ge-media')
  with check (bucket_id = 'rose-ge-media');
