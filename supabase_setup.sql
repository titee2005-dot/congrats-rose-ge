-- ==========================================
-- SQL สำหรับตั้งค่าตารางคำอวยพรออนไลน์ Rose BNK48 19th Birthday บน Supabase
-- (ทำให้การ์ดคำอวยพรขึ้นแสดงพร้อมกันทุกคนทุกเครื่องแบบ Real-time)
-- ==========================================

create table if not exists public.rose_wishes (
  id bigint generated by default as identity primary key,
  bg text not null default 'pressed-rose',
  name text not null,
  message text not null,
  img text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'hidden')),
  created_at timestamptz not null default now()
);

-- เปิดใช้งาน Row Level Security (RLS)
alter table public.rose_wishes enable row level security;

-- ลบ Policy เดิมก่อน (กรณีรันซ้ำ) แล้วสร้างใหม่
drop policy if exists "Allow public select rose_wishes" on public.rose_wishes;
drop policy if exists "Allow public insert rose_wishes" on public.rose_wishes;
drop policy if exists "Allow public update rose_wishes" on public.rose_wishes;
drop policy if exists "Allow public delete rose_wishes" on public.rose_wishes;

create policy "Allow public select rose_wishes"
  on public.rose_wishes for select
  using (true);

create policy "Allow public insert rose_wishes"
  on public.rose_wishes for insert
  with check (true);

create policy "Allow public update rose_wishes"
  on public.rose_wishes for update
  using (true);

create policy "Allow public delete rose_wishes"
  on public.rose_wishes for delete
  using (true);

-- เปิด Realtime ให้ตาราง rose_wishes อัปเดตทันทีเมื่อมีการส่งหรืออนุมัติการ์ด
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'rose_wishes'
  ) then
    alter publication supabase_realtime add table public.rose_wishes;
  end if;
end $$;
